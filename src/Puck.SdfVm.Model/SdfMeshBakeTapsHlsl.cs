using System.Globalization;
using System.Text;

namespace Puck.SdfVm;

/// <summary>Generates the include that carries the bake kernel's gradient stencil (<see cref="SdfMeshBakeTaps.Offsets"/>)
/// to the kernel, so the GPU bake and every CPU answer of a bake lattice difference the field about the same four taps.
/// The text is a pure function of the offsets, with LF line endings.</summary>
public static class SdfMeshBakeTapsHlsl {
    /// <summary>The generated include's file name, in the kernels' <c>isa</c> directory.</summary>
    public const string FileName = "sdf-bake-taps.hlsli";

    /// <summary>Generates the include.</summary>
    /// <returns>The HLSL text: <c>SdfBakeTaps</c>, the taps' directions, one <c>float3</c> per tetrahedron vertex.</returns>
    public static string Generate() {
        var text = new StringBuilder();

        void Line(string line = "") => text.Append(value: line).Append(value: '\n');
        string Real(float value) => value.ToString(format: "R", provider: CultureInfo.InvariantCulture);

        Line(line: "// Generated by `puck shaders generate` from SdfMeshBakeTaps.Offsets (SdfMeshBakeTapsHlsl); regenerate it, never edit it.");
        Line(line: "#ifndef SDF_BAKE_TAPS_HLSLI");
        Line(line: "#define SDF_BAKE_TAPS_HLSLI");
        Line();
        Line(line: "// The bake kernel's gradient stencil: a corner of the unit cube per tetrahedron vertex, scaled by the lattice's tap spacing.");
        Line(line: $"static const float3 SdfBakeTaps[{SdfMeshBakeTaps.Offsets.Length}] = {{");
        foreach (var tap in SdfMeshBakeTaps.Offsets) {
            Line(line: $"    float3({Real(value: tap.X)}, {Real(value: tap.Y)}, {Real(value: tap.Z)}),");
        }
        Line(line: "};");
        Line();
        Line(line: "#endif");

        return text.ToString();
    }
}
