using System.Text;
using Puck.SignedDistance;

namespace Puck.SdfVm;

/// <summary>Generates the shade interpreter (tier 1) and the straight-line kernels that specialize a program set
/// (tier 2) from the same typed op functions, so both tiers evaluate every op through one template.</summary>
public static partial class SdfShadeHlsl {
    /// <summary>The generated include alongside the field ISA.</summary>
    public const string FileName = "sdf-shade.hlsli";

    /// <summary>Generates declarations, the slice reader, shared typed op bodies and the interpreter. A kernel that
    /// defines <c>SDF_SHADE_EMPTY</c> before including it (the plain views and glass kernels) compiles with no
    /// interpreter and no program state: every binding folds to none.</summary>
    /// <returns>The include's text.</returns>
    public static string Generate() => GenerateCore(programs: null);

    /// <summary>Generates the include a specialized kernel compiles in place of <see cref="Generate"/>: the same
    /// declarations and op functions, then each program of <paramref name="programs"/> as straight-line phases selected by
    /// its identity, and no interpreter. A binding naming a program outside the set executes nothing, so a caller selects
    /// the kernel only for a frame whose active programs the set holds.</summary>
    /// <param name="programs">The admitted programs; duplicates by identity are ignored and order is canonical.</param>
    /// <returns>The include's text.</returns>
    /// <exception cref="ArgumentNullException"><paramref name="programs"/> is <see langword="null"/>.</exception>
    public static string Specialize(IEnumerable<SdfShadeProgram> programs) {
        ArgumentNullException.ThrowIfNull(programs);

        return GenerateCore(programs: Canonical(programs: programs));
    }
    /// <summary>Returns a program set in its canonical order: one program per identity, ordered by identity.</summary>
    /// <param name="programs">The programs.</param>
    /// <returns>The canonical set.</returns>
    /// <exception cref="ArgumentNullException"><paramref name="programs"/> is <see langword="null"/>.</exception>
    public static SdfShadeProgram[] Canonical(IEnumerable<SdfShadeProgram> programs) {
        ArgumentNullException.ThrowIfNull(programs);

        return [.. programs.DistinctBy(keySelector: static p => p.Identity).OrderBy(keySelector: static p => p.Identity, comparer: StringComparer.Ordinal)];
    }

    private static string GenerateCore(SdfShadeProgram[]? programs) {
        var text = new StringBuilder(value: "// Generated by SdfShadeHlsl. Regenerate with puck shaders generate.\n#ifndef SDF_SHADE_HLSLI\n#define SDF_SHADE_HLSLI\n");

        text.Append(value: "// Op semantics and helper content: ").Append(value: SdfShadeOps.Fingerprint).Append(value: '\n');
        text.Append(value: "#define SDF_SHADE_MAX_REGISTERS ").Append(value: SdfShadeProgram.MaxRegisters).Append(value: "u\n");
        text.Append(value: "#define SDF_SHADE_MAX_OPS ").Append(value: SdfShadeProgram.MaxOps).Append(value: "u\n");
        text.Append("#define SDF_SHADE_MAX_PHASE_WORK ").Append(SdfShadeProgram.MaxPhaseWork).Append("u\n");
        text.Append("#define SDF_SHADE_READ_PAINT ").Append((uint)SdfShadeReads.PaintCoverage).Append("u\n");
        foreach (var op in SdfShadeOps.Table) { text.Append(value: "#define SDF_SHADE_").Append(value: op.Op.ToString().ToUpperInvariant()).Append(value: ' ').Append(value: ((uint)op.Op)).Append(value: "u\n"); }
        text.Append(value: "struct SdfShadeStamp { ");
        for (var i = 0; (i < SdfShadeOps.Inputs.Count); i++) { text.Append(value: "uint4 i").Append(value: i).Append(value: "; "); }
        text.Append(value: "float4 layerRotation; float3x3 drawDirection; };\n");
        text.Append(value: "struct SdfShadeRegisters { ");
        for (var i = 0; (i < SdfShadeProgram.MaxRegisters); i++) { text.Append(value: "uint4 r").Append(value: i).Append(value: "; "); }
        text.Append(value: "};\nstruct SdfShadeOutputs { uint assigned; ");
        for (var i = 0; (i < SdfShadeProgram.OutputCapacity); i++) { text.Append(value: "uint4 o").Append(value: i).Append(value: "; "); }
        // A material's program as the stage holds it: its slice and parameter ranges, and the straight-line arm a
        // specialized kernel selected for it once a pixel (zero for the interpreter, and for none).
        text.Append(value: "};\nstruct SdfShadeBinding { uint4 range; uint arm; };\n");
        text.Append(value: "uint4 sdfShadeInput(SdfShadeStamp stamp, uint index) { switch(index) {\n");
        for (var i = 0; (i < SdfShadeOps.Inputs.Count); i++) { text.Append(value: "case ").Append(value: i).Append(value: "u: return stamp.i").Append(value: i).Append(value: ";\n"); }
        text.Append(value: "default: return 0u; } }\nuint4 sdfShadeRegister(SdfShadeRegisters regs, uint index) { switch(index & (SDF_SHADE_MAX_REGISTERS - 1u)) {\n");
        for (var i = 0; (i < SdfShadeProgram.MaxRegisters); i++) { text.Append(value: "case ").Append(value: i).Append(value: "u: return regs.r").Append(value: i).Append(value: ";\n"); }
        text.Append(value: "default: return 0u; } }\nvoid sdfShadeWriteRegister(inout SdfShadeRegisters regs, uint index, uint4 value) { switch(index & (SDF_SHADE_MAX_REGISTERS - 1u)) {\n");
        for (var i = 0; (i < SdfShadeProgram.MaxRegisters); i++) { text.Append(value: "case ").Append(value: i).Append(value: "u: regs.r").Append(value: i).Append(value: " = value; break;\n"); }
        text.Append(value: "} }\nvoid sdfShadeWriteOutputs(inout SdfShadeOutputs outputs, uint mask, uint4 value) {\noutputs.assigned |= mask;\n");
        for (var i = 0; (i < SdfShadeProgram.OutputCapacity); i++) { text.Append(value: "if ((mask & ").Append(value: (1u << i)).Append(value: "u) != 0u) outputs.o").Append(value: i).Append(value: " = value;\n"); }
        text.Append(value: "}\n");
        for (var i = 0; (i < SdfShadeOps.Inputs.Count); i++) {
            text.Append(value: "#define SDF_SHADE_INPUT_").Append(value: SdfShadeOps.Inputs[i].Name.Replace(newChar: '_', oldChar: '.').ToUpperInvariant()).Append(value: ' ').Append(value: i).Append(value: "u\n");
            var input = SdfShadeOps.Inputs[i];
            text.Append("void sdfShadeSet_").Append(input.Name.Replace('.', '_')).Append("(inout SdfShadeStamp stamp, ")
                .Append(Type(input.Type)).Append(" value) { stamp.i").Append(i).Append(" = ").Append(Encode("value", input.Type)).Append("; }\n");
        }
        text.Append(value: Helpers);
        var signatures = new Dictionary<SdfShadeOp, List<(SdfShadeType[] Args, SdfShadeType Result)>>();

        foreach (var info in SdfShadeOps.Table.Where(predicate: o => ((o.Arity > 0) && (o.Op != SdfShadeOp.Component)))) {
            var admitted = new List<(SdfShadeType[], SdfShadeType)>();

            foreach (var args in Signatures(count: info.Arity)) {
                SdfShadeType result;

                try { result = SdfShadeProgram.TypeOf(info.Op, args); } catch (SdfShadeException) { continue; }
                admitted.Add(item: (args, result));
                text.Append(value: "precise ").Append(value: Type(type: result)).Append(value: ' ').Append(value: Function(op: info.Op, types: args))
                    .Append(value: "(uint2 slice, SdfShadeStamp stamp, uint immediate");
                for (var i = 0; (i < args.Length); i++) { text.Append(value: ", ").Append(value: Type(type: args[i])).Append(value: ' ').Append(value: ((char)('a' + i))); }
                text.Append(value: ") { precise ").Append(value: Type(type: result)).Append(value: " result = ").Append(value: info.Template).Append(value: "; return result; }\n");
            }
            signatures.Add(key: info.Op, value: admitted);
        }
        if (programs is null) {
            Interpreter(signatures: signatures, text: text);
        } else {
            Arms(programs: programs, text: text);
        }
        text.Append(Invocation).Append("\n#endif\n");
        return text.ToString();
    }
    // Tier 1. The plain kernels define SDF_SHADE_EMPTY: their binding is constant none, so every program branch of the
    // stages folds away and no interpreter state is allocated.
    private static void Interpreter(Dictionary<SdfShadeOp, List<(SdfShadeType[] Args, SdfShadeType Result)>> signatures, StringBuilder text) {
        text.Append(value: """
#ifndef SDF_SHADE_EMPTY

void sdfShadeInterpret(uint2 slice, uint2 parameters, uint phase, SdfShadeStamp stamp, out SdfShadeOutputs outputs) {
    SdfShadeRegisters regs = (SdfShadeRegisters)0;
    outputs = (SdfShadeOutputs)0;
    if (phase >= 3u) return;
    uint4 header = sdfShadeRead(slice, phase);
    uint count = min(header.y, SDF_SHADE_MAX_OPS);
    if (header.x > slice.y || count > (slice.y - header.x) / 3u) return;
    [loop] for (uint i = 0u; i < count; i++) {
        uint offset = header.x + i * 3u;
        uint4 op = sdfShadeRead(slice, offset);
        uint4 indices = sdfShadeRead(slice, offset + 1u);
        uint4 types = sdfShadeRead(slice, offset + 2u);
        indices &= SDF_SHADE_MAX_REGISTERS - 1u;
        op.y &= SDF_SHADE_MAX_REGISTERS - 1u;
        uint4 a = sdfShadeRegister(regs, indices.x), b = sdfShadeRegister(regs, indices.y);
        uint4 c = sdfShadeRegister(regs, indices.z), d = sdfShadeRegister(regs, indices.w);
        uint signature = types.x | (types.y << 4u) | (types.z << 8u) | (types.w << 12u);
        uint4 value = 0u;
        switch (op.x) {
        case SDF_SHADE_CONSTANT: value = sdfShadeRead(slice, op.w); break;
        case SDF_SHADE_PARAMETER: value = sdfShadeRead(parameters, op.w); break;
        case SDF_SHADE_INPUT: value = sdfShadeInput(stamp, op.w); break;
        case SDF_SHADE_COMPONENT: value.x = op.w == 0u ? a.x : op.w == 1u ? a.y : op.w == 2u ? a.z : op.w == 3u ? a.w : 0u; break;

""");
        foreach (var (op, variants) in signatures) {
            text.Append(value: "        case SDF_SHADE_").Append(value: op.ToString().ToUpperInvariant()).Append(value: ": switch (signature) {\n");
            foreach (var (args, result) in variants) {
                var operands = args.Select(selector: (type, i) => Decode(((char)('a' + i)).ToString(), type)).ToArray();

                text.Append(value: "            case ").Append(value: Signature(types: args)).Append(value: "u: { precise ").Append(value: Type(type: result))
                    .Append(value: " result = ").Append(value: Function(op: op, types: args)).Append(value: "(slice, stamp, op.w, ").AppendJoin(", ", operands)
                    .Append(value: "); value = ").Append(value: Encode(type: result, value: "result")).Append(value: "; break; }\n");
            }
            text.Append(value: "        } break;\n");
        }
        text.Append(value: "        }\n        sdfShadeWriteRegister(regs, op.y, value);\n        sdfShadeWriteOutputs(outputs, op.z >> 8u, value);\n        sdfWorkSteps++;\n    }\n}\n");
        text.Append(value: """
uint sdfShadeArm(uint2 slice) { return 0u; }
bool sdfShadeHas(SdfShadeBinding binding, uint phase) { return binding.range.y != 0u && sdfShadeRead(binding.range.xy, phase).y != 0u; }
uint sdfShadeReadsOf(SdfShadeBinding binding) { return binding.range.y != 0u ? sdfShadeRead(binding.range.xy, 0u).w : 0u; }
void sdfShadeExecute(SdfShadeBinding binding, uint phase, SdfShadeStamp stamp, out SdfShadeOutputs outputs) {
    sdfShadeInterpret(binding.range.xy, binding.range.zw, phase, stamp, outputs);
}
#else
uint sdfShadeArm(uint2 slice) { return 0u; }
bool sdfShadeHas(SdfShadeBinding binding, uint phase) { return false; }
uint sdfShadeReadsOf(SdfShadeBinding binding) { return 0u; }
void sdfShadeExecute(SdfShadeBinding binding, uint phase, SdfShadeStamp stamp, out SdfShadeOutputs outputs) { outputs = (SdfShadeOutputs)0; }
#endif

""");
    }
    // Tier 2. Each program is an arm of straight-line phases; the arm is chosen once a pixel by the identity the program's
    // header carries (SdfShadeProgram.IdentityVector), and a phase the program does not declare is statically absent.
    private static void Arms(SdfShadeProgram[] programs, StringBuilder text) {
        for (var arm = 1; (arm <= programs.Length); arm++) {
            var program = programs[arm - 1];

            for (var phase = 0; (phase < 3); phase++) {
                if (program.Phases[phase].Count == 0) { continue; }
                text.Append(System.Globalization.CultureInfo.InvariantCulture, $"SdfShadeOutputs sdfShadeArm{arm}Phase{phase}(uint2 slice, uint2 parameters, SdfShadeStamp stamp) {{\n")
                    .Append(value: Emit(program: program, phase: ((SdfShadePhase)phase))).Append(value: "return outputs;\n}\n");
            }
        }
        text.Append(value: "uint sdfShadeArm(uint2 slice) {\n");
        if (programs.Length != 0) {
            text.Append(System.Globalization.CultureInfo.InvariantCulture, $"uint4 a = sdfShadeRead(slice, {SdfShadeProgram.IdentityVector}u), b = sdfShadeRead(slice, {(SdfShadeProgram.IdentityVector + 1)}u);\n");
            for (var arm = 1; (arm <= programs.Length); arm++) {
                var words = programs[arm - 1].Words.Slice(start: (SdfShadeProgram.IdentityVector * 4), length: (SdfShadeProgram.IdentityVectors * 4)).ToArray()
                    .Select(selector: static w => w.ToString(provider: System.Globalization.CultureInfo.InvariantCulture) + "u").ToArray();

                text.Append(System.Globalization.CultureInfo.InvariantCulture, $"if (all(a == uint4({string.Join(',', words[..4])})) && all(b == uint4({string.Join(',', words[4..])}))) return {arm}u;\n");
            }
        }
        text.Append(value: "return 0u;\n}\nuint sdfShadeArmPhases(uint arm) {\nswitch (arm) {\n");
        for (var arm = 1; (arm <= programs.Length); arm++) {
            var mask = 0u;

            for (var phase = 0; (phase < 3); phase++) { if (programs[arm - 1].Phases[phase].Count != 0) { mask |= (1u << phase); } }
            text.Append(System.Globalization.CultureInfo.InvariantCulture, $"case {arm}u: return {mask}u;\n");
        }
        text.Append(value: "default: return 0u;\n}\n}\nuint sdfShadeReadsOf(SdfShadeBinding binding) {\nswitch (binding.arm) {\n");
        for (var arm = 1; (arm <= programs.Length); arm++) {
            text.Append(System.Globalization.CultureInfo.InvariantCulture, $"case {arm}u: return {((uint)programs[arm - 1].Reads)}u;\n");
        }
        text.Append(value: "default: return 0u;\n}\n}\nbool sdfShadeHas(SdfShadeBinding binding, uint phase) { return ((sdfShadeArmPhases(binding.arm) >> phase) & 1u) != 0u; }\n");
        text.Append(value: "void sdfShadeExecute(SdfShadeBinding binding, uint phase, SdfShadeStamp stamp, out SdfShadeOutputs outputs) {\noutputs = (SdfShadeOutputs)0;\nswitch (binding.arm) {\n");
        for (var arm = 1; (arm <= programs.Length); arm++) {
            text.Append(System.Globalization.CultureInfo.InvariantCulture, $"case {arm}u:\n");
            for (var phase = 0; (phase < 3); phase++) {
                if (programs[arm - 1].Phases[phase].Count == 0) { continue; }
                text.Append(System.Globalization.CultureInfo.InvariantCulture, $"if (phase == {phase}u) outputs = sdfShadeArm{arm}Phase{phase}(binding.range.xy, binding.range.zw, stamp);\n");
            }
            text.Append(value: "break;\n");
        }
        text.Append(value: "default: break;\n}\n}\n");
    }
    /// <summary>Emits one admitted phase as precise locals using exactly the interpreter's generated op functions.</summary>
    /// <param name="program">The admitted program.</param>
    /// <param name="phase">The phase whose instructions are emitted.</param>
    /// <returns>The statements, which declare <c>regs</c> and <c>outputs</c> and read <c>slice</c>, <c>parameters</c> and
    /// <c>stamp</c>.</returns>
    /// <exception cref="ArgumentNullException"><paramref name="program"/> is <see langword="null"/>.</exception>
    public static string Emit(SdfShadeProgram program, SdfShadePhase phase) {
        ArgumentNullException.ThrowIfNull(program);
        var text = new StringBuilder();

        text.Append(value: "SdfShadeRegisters regs = (SdfShadeRegisters)0;\nSdfShadeOutputs outputs = (SdfShadeOutputs)0;\n");
        var ordinal = 0;

        foreach (var instruction in program.Phases[((int)phase)]) {
            var result = instruction.Result;
            var args = instruction.Operands.Select(selector: a => Decode($"regs.r{a.Index}", a.Type)).ToArray();
            // A constant is folded into the code from the words the interpreter reads, bit for bit.
            var value = instruction.Op switch {
                SdfShadeOp.Constant => Decode("uint4(" + string.Join(",", program.Words.Slice(checked((int)instruction.Immediate * 4), 4).ToArray().Select(w => $"{w}u")) + ")", result.Type),
                SdfShadeOp.Parameter => Decode($"sdfShadeRead(parameters, {instruction.Immediate}u)", result.Type),
                SdfShadeOp.Input => Decode($"stamp.i{instruction.Immediate}", result.Type),
                SdfShadeOp.Component => SdfShadeOps.Width(instruction.Operands[0].Type) == 1 ? args[0] : $"{args[0]}[{instruction.Immediate}u]",
                _ => $"{Function(op: instruction.Op, types: instruction.Operands.Select(selector: a => a.Type).ToArray())}(slice, stamp, {instruction.Immediate}u, {string.Join(", ", args)})",
            };

            var local = $"v{ordinal++}";

            text.Append(value: "precise ").Append(value: Type(type: result.Type)).Append(value: ' ').Append(value: local).Append(value: " = ").Append(value: value).Append(value: ";\n");
            text.Append(value: "regs.r").Append(value: result.Index).Append(value: " = ").Append(value: Encode(local, result.Type)).Append(value: ";\n");
            if (instruction.OutputMask != 0) { text.Append(value: "sdfShadeWriteOutputs(outputs, ").Append(value: instruction.OutputMask).Append(value: "u, regs.r").Append(value: result.Index).Append(value: ");\n"); }
            text.Append("sdfWorkSteps++;\n");
        }
        return text.ToString();
    }

    private static string Function(SdfShadeOp op, SdfShadeType[] types) => $"sdfShade_{op}_{Signature(types: types)}";
    private static uint Signature(SdfShadeType[] types) { var value = 0U; for (var i = 0; (i < types.Length); i++) { value |= (((uint)types[i]) << (4 * i)); } return value; }
    private static string Type(SdfShadeType type) => ((SdfShadeOps.IsUInt(type: type) ? "uint" : "float") + ((SdfShadeOps.Width(type: type) == 1) ? "" : SdfShadeOps.Width(type: type).ToString(provider: System.Globalization.CultureInfo.InvariantCulture)));
    private static string Decode(string value, SdfShadeType type) => (((SdfShadeOps.IsUInt(type: type) ? value : $"asfloat({value})") + ".") + "xyzw"[..SdfShadeOps.Width(type: type)]);
    private static string Encode(string value, SdfShadeType type) {
        var bits = (SdfShadeOps.IsUInt(type: type) ? value : $"asuint({value})");

        return ((SdfShadeOps.Width(type: type) == 4) ? bits : $"uint4({bits}{string.Concat(values: Enumerable.Repeat(", 0u", (4 - SdfShadeOps.Width(type: type))))})");
    }
    private static IEnumerable<SdfShadeType[]> Signatures(int count) {
        if (count == 0) { yield return []; yield break; }
        foreach (var prefix in Signatures(count: (count - 1))) {
            foreach (var type in Enum.GetValues<SdfShadeType>()) { yield return [.. prefix, type]; }
        }
    }

    private const string Helpers = """
// The one read door: relative range first, whole allocation second. No authored address is absolute.
uint4 sdfShadeRead(uint2 slice, uint relative) {
    if (relative >= slice.y || !sdfProgramRange(slice.x, slice.y, 1u)) return 0u;
    return asuint(sdfWords[slice.x + relative]);
}
precise float3 sdfShadeToLayer(SdfShadeStamp stamp, float3 v) { return rotatePointByInverseQuaternion(v, stamp.layerRotation); }
precise float3 sdfShadeToWorld(SdfShadeStamp stamp, float3 v) { return rotatePointByQuaternion(v, stamp.layerRotation); }
precise float3 sdfShadeDrawDirection(SdfShadeStamp stamp, float3 v) { return mul(stamp.drawDirection, v); }
precise float3 sdfShadeTilt(float3 normal, float3 slope, float angle) {
    precise float3 tangent = slope - normal * dot(slope, normal);
    precise float magnitude = length(tangent);
    precise float theta = min(atan(magnitude), clamp(angle, 0.0, 3.14159265358979323846));
    return magnitude > 0.0 ? normalize(normal * cos(theta) + (tangent / magnitude) * sin(theta)) : normal;
}
precise float sdfShadeShape(uint2 slice, uint relative, float3 position, float footprint) {
    if (relative > slice.y || slice.y - relative < 7u) return 0.0;
    uint4 header = sdfShadeRead(slice, relative);
    precise float4 data0 = asfloat(sdfShadeRead(slice, relative + 1u));
    precise float4 data1 = asfloat(sdfShadeRead(slice, relative + 2u));
    precise float4 scale = asfloat(sdfShadeRead(slice, relative + 3u));
    precise float3 center = asfloat(sdfShadeRead(slice, relative + 4u)).xyz;
    precise float3 extent = asfloat(sdfShadeRead(slice, relative + 5u)).xyz;
    precise float4 rotation = asfloat(sdfShadeRead(slice, relative + 6u));
    // Like paints, only the footprint neighbourhood needs the expensive exact field. Outside the bound the
    // positive box lower bound preserves coverage; shape is a coverage-distance op, not a geometry query.
    precise float3 outside = abs(position - center) - extent;
    precise float bound = max(outside.x, max(outside.y, outside.z));
    if (header.z == 0u && bound > max(footprint, 0.0)) return bound;
    uint table = relative + 7u;
    uint vectors = (header.y + 3u) / 4u;
    if (header.y > SDF_MAX_CONVEX_VERTICES * 2u || table > slice.y || vectors > slice.y - table || !sdfProgramRange(slice.x, slice.y, 1u)) return 0.0;
    // The existing helpers receive an absolute address only after the complete owned side table passes this door.
    if (header.x == SDF_SHAPE_SWEEP) data0.x = asfloat(slice.x + table);
    if (header.x == SDF_SHAPE_CONVEX_POLYGON) {
        uint reference = asuint(data0.x);
        data0.x = asfloat(((slice.x + table) << SDF_CONVEX_COUNT_BITS) | (reference & ((1u << SDF_CONVEX_COUNT_BITS) - 1u)));
    }
    return evaluateShape(header.x, rotatePointByInverseQuaternion(position / scale.xyz, rotation), data0, data1) * scale.w;
}
// Called by the stage for every assigned output, using its base/default value and declared domain.
precise float4 sdfShadeSanitize(float4 value, float4 fallback, float4 low, float4 high) {
    value = float4(isfinite(value.x) ? value.x : fallback.x, isfinite(value.y) ? value.y : fallback.y,
        isfinite(value.z) ? value.z : fallback.z, isfinite(value.w) ? value.w : fallback.w);
    return clamp(value, low, high);
}
precise float3 sdfShadeSanitizeNormal(float3 value, float3 fallback) {
    precise float squared = dot(value, value);
    return all(isfinite(value)) && isfinite(squared) && squared > 0.0 ? value / sqrt(squared) : fallback;
}

""";
}
