using System.Text;
using Puck.SignedDistance;

namespace Puck.SdfVm;

/// <summary>Emits the field interpreter's dispatch from the instruction catalogue.</summary>
public static class SdfFieldHlsl {
    /// <summary>The generated include's name.</summary>
    public const string FileName = "sdf-field-map.hlsli";

    /// <summary>Produces the interpreter's shader arms and payload reads.</summary>
    public static string Generate() {
        var output = new StringBuilder("// Generated by `puck shaders generate` from the field catalogues.\n");

        foreach (var (op, action) in SdfFieldOps.ShaderActions()) {
            output.Append("case SDF_OP_").Append(SdfIsaHlsl.UpperSnake(name: op.ToString())).Append(": {\n");
            if ((action.Operands & SdfShaderOperands.Data0) != 0) { output.Append("    SDF_VM_LOAD_DATA0;\n"); }
            if ((action.Operands & SdfShaderOperands.Data1) != 0) { output.Append("    SDF_VM_LOAD_DATA1;\n"); }
            output.Append(action.Code).Append("\n}\n");
        }

        return output.ToString();
    }
}
