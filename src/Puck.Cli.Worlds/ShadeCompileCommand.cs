using System.CommandLine;
using System.Text;
using Puck.SdfVm;
using Puck.Shaders;
using Puck.World;
using Puck.World.Transpiler;

namespace Puck.Cli;

/// <summary>Plans or compiles a document's declared shade set without creating a World or a GPU device.</summary>
public static class ShadeCompileCommand {
    public static Command Create() {
        var world = new Argument<string>("world") { Description = "One world source or document; neighbours are not visited." };
        var tree = new Option<string?>("--tree") { Description = "Kernel source tree; defaults to the deployed SDF tree." };
        var cache = new Option<string?>("--cache") { Description = "Compiler cache; defaults to the shared shader cache." };
        var target = new Option<string>("--target") { DefaultValueFactory = _ => "dxil", Description = "dxil or spirv." };
        target.AcceptOnlyFromAmong("dxil", "spirv");
        var compile = new Option<bool>("--compile") { Description = "Run DXC on misses, then repeat to prove a warm round invokes no tools." };
        var includes = new Option<bool>("--includes") { Description = "List each kernel's include paths and UTF-8 bytes." };
        var command = new Command("specialize", "Audit authored shade specialization offline: programs, generated bytes, include bytes and DXC invocations.") { world, tree, cache, target, compile, includes };
        command.SetAction(async (result, cancellationToken) => {
            var path = Path.GetFullPath(result.GetRequiredValue(world));
            var machines = CliWorldVocabulary.EnsureInstalled();
            if (!WorldDefinitionFileSource.TryComposeDocumentTree(catalog: machines, catalogFingerprint: CliWorldVocabulary.Fingerprint(machines),
                documents: WorldCompileSession.Shared, path: path, reason: out var reason, tree: out var document)) {
                return CliExit.Refuse("shaders specialize", path, reason);
            }
            if (!WorldDefinitionLoader.TryReadPublishable(catalog: machines, definition: out var definition,
                documentDirectory: WorldDocumentPaths.DirectoryOf(path), json: document!.ToJsonString(), reason: out reason, sourceName: path)) {
                return CliExit.Refuse("shaders specialize", path, reason);
            }
            var programs = SdfShadeHlsl.Canonical(WorldRenderSettings.DeclaredShades(definition!));
            var compiler = new ShaderCompiler(result.GetValue(cache) ?? ShaderCompiler.DefaultCacheDirectory);
            var sources = SdfShadeKernels.SourcesOf(result.GetValue(tree) ?? SdfKernelSet.DeployedTree);
            var plans = SdfShadeKernels.Plan(programs, compiler, result.GetValue(target) == "spirv" ? ShaderTarget.Spirv : ShaderTarget.Dxil, sources);
            var generated = SdfShadeHlsl.Specialize(programs);
            var sourceSlots = new SdfKernelSource?[SdfKernelSet.Kernels.Count];
            for (var index = 0; index < sources.Count; index++) { sourceSlots[(int)SdfShadeKernels.Specialized[index]] = sources[index]; }
            var kernels = new SdfKernelSet(new ReadOnlyMemory<byte>[SdfKernelSet.Kernels.Count], sourceSlots);
            var unrelated = SdfKernelSet.Kernels.First(kernel => !SdfShadeKernels.Specialized.Contains(kernel));
            var identity = SdfShadeKernels.InterpreterOf(kernels);
            var unrelatedStable = identity == SdfShadeKernels.InterpreterOf(kernels.With(unrelated, new byte[] { 1 }));
            var specializedChanges = identity != SdfShadeKernels.InterpreterOf(kernels.With(SdfShadeKernels.Specialized[0], new byte[] { 1 }, sources[0]));
            Console.WriteLine($"unrelated-kernel-stable={unrelatedStable} specialized-kernel-invalidates={specializedChanges}");
            if (!unrelatedStable || !specializedChanges) { return CliExit.Failed; }
            Console.WriteLine($"programs={programs.Length} generated-bytes={Encoding.UTF8.GetByteCount(generated)} counter-updates={generated.Split("sdfWorkShadeOperations", StringSplitOptions.None).Length - 1}");
            foreach (var program in programs) {
                Console.WriteLine($"program={program.Name} identity={program.Identity} values={program.Straight.Phases.Sum(p => p.Count)}");
            }
            foreach (var (kernel, plan) in plans) {
                Console.WriteLine($"kernel={SdfKernelSet.StemOf(kernel)} target={plan.Target} includes={plan.Includes.Count} closure-bytes={plan.ClosureBytes} cached={compiler.IsCached(plan)} inputs={plan.Inputs}");
                if (result.GetValue(includes)) {
                    foreach (var dependency in plan.Includes) {
                        Console.WriteLine($"include={CliPaths.ToDisplay(dependency.Path)} bytes={Encoding.UTF8.GetByteCount(plan.Contents[dependency.Path])}");
                    }
                }
            }
            var misses = plans.Where(p => !compiler.IsCached(p.Plan)).ToArray();
            Console.WriteLine($"planned-dxc={misses.Length} planned-hlsl-bytes={misses.Sum(p => p.Plan.ClosureBytes)}");
            if (result.GetValue(compile)) {
                for (var round = 0; round < 2; round++) {
                    plans = SdfShadeKernels.Plan(programs, compiler, plans[0].Plan.Target, sources);
                    var results = await Task.WhenAll(plans.Select(async item => (item.Plan, Result: await ShaderCompileTurns.CompileAsync(compiler, item.Plan, cancellationToken))));
                    foreach (var item in results.Where(p => !p.Result.IsSuccess)) {
                        foreach (var diagnostic in item.Result.Diagnostics) { Console.Error.WriteLine(diagnostic.Message); }
                    }
                    Console.WriteLine($"round={round + 1} dxc={results.Count(p => p.Result.Compiled)} hlsl-bytes={results.Where(p => p.Result.Compiled).Sum(p => p.Plan.ClosureBytes)} cache-hits={results.Count(p => !p.Result.Compiled)}");
                    if (results.Any(p => !p.Result.IsSuccess)) { return CliExit.Failed; }
                }
            }
            return CliExit.Success;
        });
        return command;
    }
}
