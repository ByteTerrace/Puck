using System.Globalization;
using System.Text;
using Puck.Abstractions.Sources;

namespace Puck.Shaders;

/// <summary>
/// Generates the include that carries the luma weights of the Y'CbCr matrices (<see cref="ImageSourceConversion.Bt601Kr"/>
/// and the rest) to every kernel, so a kernel decoding Y'CbCr or weighing a linear Rec. 709 colour's luminance reads the
/// constants the CPU reference states rather than its own literals. The text is a pure function of those constants, with
/// LF line endings.
/// </summary>
public static class ShaderLumaHlsl {
    /// <summary>The generated include's repository-relative path, with forward slashes.</summary>
    public const string Path = "src/Puck.Shaders/Assets/Shaders/Shared/luma.hlsli";

    /// <summary>Generates the include.</summary>
    /// <returns>The HLSL text: each matrix's <c>Kr</c> and <c>Kb</c> as <c>float</c> constants, and
    /// <c>PuckRec709Luminance</c>, the linear Rec. 709 luminance weights.</returns>
    public static string Generate() {
        var text = new StringBuilder();

        void Line(string line = "") => text.Append(value: line).Append(value: '\n');
        string Real(double value) => ((float)value).ToString(format: "R", provider: CultureInfo.InvariantCulture);
        void Constant(string name, double value) => Line(line: $"static const float {name} = {Real(value: value)};");

        Line(line: "// Generated by `puck shaders generate` from Puck.Abstractions.Sources.ImageSourceConversion (ShaderLumaHlsl); regenerate it, never edit it.");
        Line(line: "#ifndef PUCK_LUMA_HLSLI");
        Line(line: "#define PUCK_LUMA_HLSLI");
        Line();
        Line(line: "// Each Y'CbCr matrix's red and blue shares of luma; green takes the rest.");
        Constant(name: "PuckBt601Kr", value: ImageSourceConversion.Bt601Kr);
        Constant(name: "PuckBt601Kb", value: ImageSourceConversion.Bt601Kb);
        Constant(name: "PuckBt709Kr", value: ImageSourceConversion.Bt709Kr);
        Constant(name: "PuckBt709Kb", value: ImageSourceConversion.Bt709Kb);
        Constant(name: "PuckBt2020Kr", value: ImageSourceConversion.Bt2020Kr);
        Constant(name: "PuckBt2020Kb", value: ImageSourceConversion.Bt2020Kb);
        Line();
        Line(line: "// A linear Rec. 709 colour's luminance weights, its Y.");
        Line(line: $"static const float3 PuckRec709Luminance = float3({Real(value: ImageSourceConversion.Bt709Kr)}, " +
            $"{Real(value: (1.0 - ImageSourceConversion.Bt709Kr - ImageSourceConversion.Bt709Kb))}, {Real(value: ImageSourceConversion.Bt709Kb)});");
        Line();
        Line(line: "#endif");

        return text.ToString();
    }
}
