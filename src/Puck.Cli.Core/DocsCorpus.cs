namespace Puck.Cli;

/// <summary>
/// The hand-written documentation corpus: every markdown page a reader or an agent takes as current, derived from the
/// tree and never listed by hand. <c>puck docs links</c> checks it, and <c>puck affected</c> selects that check when a
/// change touches one of its pages. A page belongs when its path is one of:
/// <list type="bullet">
/// <item><description><c>AGENTS.md</c> or <c>README.md</c> at the repository root;</description></item>
/// <item><description>any markdown under <c>docs/</c>, except the image packs in the subdirectories of
/// <c>docs/game/art/</c>;</description></item>
/// <item><description>any markdown under <c>.claude/skills/</c>, except a skill's <c>evals/</c>;</description></item>
/// <item><description>any markdown under <c>worlds/</c>;</description></item>
/// <item><description>every <c>README.md</c> under <c>src/</c> or <c>tests/</c>.</description></item>
/// </list>
/// A page a verb generates (its opening lines say <c>Generated by</c> and <c>do not hand-edit</c>) is the code's own
/// output, which its generator checks, so it is left out.
/// </summary>
public static class DocsCorpus {
    private const int GeneratedHeaderLines = 5;
    private const string GeneratedMarker = "do not hand-edit";

    /// <summary>Returns whether a repository-relative path names a page of the corpus, by its path alone.</summary>
    /// <param name="relativePath">The path, repository-relative with forward slashes.</param>
    /// <returns><see langword="true"/> when the path is a corpus page; a generated page is still one by path.</returns>
    public static bool IsDocument(string relativePath) {
        if (!relativePath.EndsWith(
            comparisonType: StringComparison.OrdinalIgnoreCase,
            value: ".md"
        )) {
            return false;
        }

        if (relativePath is "AGENTS.md" or "README.md") {
            return true;
        }

        var segments = relativePath.Split(separator: '/');

        return segments[0] switch {
            "docs" => !((segments.Length > 4) && (segments[1] == "game") && (segments[2] == "art")),
            ".claude" => ((segments.Length > 2) && (segments[1] == "skills") && !segments.Contains(value: "evals")),
            "worlds" => true,
            "src" or "tests" => (segments[^1] == "README.md"),
            _ => false,
        };
    }
    /// <summary>Returns whether a page's opening lines declare it generated output that is never hand-edited.</summary>
    /// <param name="lines">The page's lines.</param>
    /// <returns><see langword="true"/> when one of the first lines opens with <c>Generated by</c> and says
    /// <c>do not hand-edit</c>.</returns>
    public static bool IsGenerated(IReadOnlyList<string> lines) =>
        lines.Take(count: GeneratedHeaderLines).Any(predicate: static line => (line.StartsWith(
            comparisonType: StringComparison.Ordinal,
            value: "Generated by "
        ) && line.Contains(
            comparisonType: StringComparison.OrdinalIgnoreCase,
            value: GeneratedMarker
        )));
    /// <summary>Returns whether a page is durable: everything outside <c>docs/plans/</c>, whose pages are rechecked
    /// before use and deleted when consumed, so they may cite a <c>file:line</c>.</summary>
    /// <param name="relativePath">The page's path, repository-relative with forward slashes.</param>
    /// <returns><see langword="true"/> for a durable page.</returns>
    public static bool IsDurable(string relativePath) => !relativePath.StartsWith(
        comparisonType: StringComparison.Ordinal,
        value: "docs/plans/"
    );
    /// <summary>Lists the corpus: every markdown file git tracks, or holds untracked but not ignored, that exists in the
    /// working tree, belongs by <see cref="IsDocument"/> and is not generated.</summary>
    /// <param name="repositoryRoot">The repository root.</param>
    /// <param name="documents">The pages, repository-relative with forward slashes, in ordinal order.</param>
    /// <param name="error">Why git could not list the tree, or empty.</param>
    /// <returns><see langword="true"/> when the tree was listed.</returns>
    public static bool TryEnumerate(string repositoryRoot, out IReadOnlyList<string> documents, out string error) {
        documents = [];

        var listing = CliGit.Run(repositoryRoot, "ls-files", "-z", "--cached", "--others", "--exclude-standard", "--", "*.md");

        if (listing.ExitCode != 0) {
            error = $"git ls-files failed: {listing.Stderr.Trim()}";

            return false;
        }

        documents = [.. listing.Stdout.Split(
            options: StringSplitOptions.RemoveEmptyEntries,
            separator: '\0'
        )
            .Distinct(comparer: StringComparer.Ordinal)
            .Where(predicate: IsDocument)
            .Where(predicate: path => {
                var full = Path.Combine(
                    path1: repositoryRoot,
                    path2: path
                );

                return (File.Exists(path: full) && !IsGenerated(lines: [.. File.ReadLines(path: full).Take(count: GeneratedHeaderLines)]));
            })
            .Order(comparer: StringComparer.Ordinal)];
        error = string.Empty;

        return true;
    }
}
